local M = {}

function M.get(c, opts)
  local s = opts.styles
  return {
    Comment = vim.tbl_extend("force", { fg = c.comment }, s.comments),
    Constant = { fg = c.keyword },
    String = { fg = c.string },
    Character = { fg = c.string },
    Number = { fg = c.keyword },
    Boolean = { fg = c.keyword },
    Float = { fg = c.keyword },
    Identifier = vim.tbl_extend("force", { fg = c.fg }, s.variables),
    Function = vim.tbl_extend("force", { fg = c.func }, s.functions),
    Statement = { fg = c.keyword },
    Conditional = { fg = c.keyword },
    Repeat = { fg = c.keyword },
    Label = { fg = c.label },
    Operator = { fg = c.fg },
    Keyword = vim.tbl_extend("force", { fg = c.keyword }, s.keywords),
    Exception = { fg = c.keyword },
    PreProc = { fg = c.keyword },
    Include = { fg = c.keyword },
    Define = { fg = c.keyword },
    Macro = { fg = c.special },
    PreCondit = { fg = c.keyword },
    Type = { fg = c.type },
    StorageClass = { fg = c.keyword },
    Structure = { fg = c.type },
    Typedef = { fg = c.type },
    Special = { fg = c.special },
    SpecialChar = { fg = c.special },
    Tag = { fg = c.type },
    Delimiter = { fg = c.fg_dim },
    SpecialComment = { fg = c.doc_comment },
    Debug = { fg = c.warning },
    Underlined = { underline = true },
    Bold = { bold = true },
    Italic = { italic = true },
    Ignore = { fg = c.comment },
    Error = { fg = c.error },
    Todo = { fg = c.info_fg, bg = c.info_bg, bold = true },

    diffAdded = { fg = c.git_add },
    diffRemoved = { fg = c.git_delete },
    diffChanged = { fg = c.git_change },
    diffOldFile = { fg = c.danger_fg },
    diffNewFile = { fg = c.success_fg },
    diffFile = { fg = c.type },
    diffLine = { fg = c.fg_dim },
    diffIndexLine = { fg = c.label },

    markdownH1 = { fg = c.h1, bold = true },
    markdownH2 = { fg = c.h2, bold = true },
    markdownH3 = { fg = c.h3, bold = true },
    markdownH4 = { fg = c.h4, bold = true },
    markdownH5 = { fg = c.h5, bold = true },
    markdownH6 = { fg = c.h6, bold = true },
    markdownCode = { fg = c.gold_400 },
    markdownCodeBlock = { fg = c.fg },
    markdownLinkText = { fg = c.gold_300 },
    markdownUrl = { fg = c.gold_300, underline = true },
  }
end

return M
